/**
 * Converts any string into a clean URL-friendly slug
 * e.g. "Amma's Kitchen" -> "ammas-kitchen"
 * "Punjab Rasoi" -> "punjab-rasoi"
 */
export function slugify(text) {
  if (!text) return "";
  return String(text)
    .toLowerCase()
    .trim()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

